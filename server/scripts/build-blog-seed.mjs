/**
 * Writes db/migrations/011_seed_blog_posts.sql from src/db/seed/blogPosts.js.
 * Run: node scripts/build-blog-seed.mjs
 * The migration inserts each post once (ON CONFLICT DO NOTHING), so edits
 * made later in the dashboard are never overwritten.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { blogPosts } from '../src/db/seed/blogPosts.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(__dirname, '../src/db/migrations/011_seed_blog_posts.sql');

const rows = blogPosts.map((p) => ({
  slug: p.slug,
  title: p.title,
  excerpt: p.excerpt,
  body: p.body,
  cover_url: `/images/blog/${p.slug}/cover.webp`,
  tags: p.tags,
  author: 'B-Code Team',
  published_at: p.publishedAt,
}));

const json = JSON.stringify(rows, null, 1);
if (json.includes('$seed$')) throw new Error('Seed text must not contain the $seed$ delimiter');

const sql = `-- Launch articles for the blog (generated by scripts/build-blog-seed.mjs — edit the JS source, not this file).
INSERT INTO blog_posts (slug, title, excerpt, body, cover_url, tags, author, status, published_at)
SELECT slug, title, excerpt, body, cover_url, tags, author, 'published', published_at
FROM jsonb_to_recordset($seed$${json}$seed$::jsonb)
  AS x(slug TEXT, title JSONB, excerpt JSONB, body JSONB, cover_url TEXT, tags JSONB, author TEXT, published_at TIMESTAMPTZ)
ON CONFLICT (slug) DO NOTHING;
`;

fs.writeFileSync(out, sql);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${rows.length} posts, ${Math.round(sql.length / 1024)} KB)`);
