/**
 * Writes the blog seed migrations from the article sources in src/db/seed/.
 * Run: node scripts/build-blog-seed.mjs
 * Each migration inserts its posts once (ON CONFLICT DO NOTHING), so edits
 * made later in the dashboard are never overwritten.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { blogPosts } from '../src/db/seed/blogPosts.js';
import { blogPostsBatch2 } from '../src/db/seed/blogPostsBatch2.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const migrations = path.resolve(__dirname, '../src/db/migrations');

const toJson = (rows) => {
  const json = JSON.stringify(rows, null, 1);
  if (json.includes('$seed$')) throw new Error('Seed text must not contain the $seed$ delimiter');
  return json;
};

const write = (file, sql, count) => {
  fs.writeFileSync(path.join(migrations, file), sql);
  console.log(`Wrote ${file} (${count} posts, ${Math.round(sql.length / 1024)} KB)`);
};

// 011 — launch articles, published.
const launch = blogPosts.map((p) => ({
  slug: p.slug,
  title: p.title,
  excerpt: p.excerpt,
  body: p.body,
  cover_url: `/images/blog/${p.slug}/cover.webp`,
  tags: p.tags,
  author: 'B-Code Team',
  published_at: p.publishedAt,
}));

write(
  '011_seed_blog_posts.sql',
  `-- Launch articles for the blog (generated by scripts/build-blog-seed.mjs — edit the JS source, not this file).
INSERT INTO blog_posts (slug, title, excerpt, body, cover_url, tags, author, status, published_at)
SELECT slug, title, excerpt, body, cover_url, tags, author, 'published', published_at
FROM jsonb_to_recordset($seed$${toJson(launch)}$seed$::jsonb)
  AS x(slug TEXT, title JSONB, excerpt JSONB, body JSONB, cover_url TEXT, tags JSONB, author TEXT, published_at TIMESTAMPTZ)
ON CONFLICT (slug) DO NOTHING;
`,
  launch.length
);

// 014 — second batch, saved as drafts: they contain [VERIFY] notes to check before publishing.
const batch2 = blogPostsBatch2.map((p) => ({
  slug: p.slug,
  title: p.title,
  excerpt: p.excerpt,
  body: p.body,
  cover_url: `/images/blog/${p.slug}/cover.webp`,
  tags: p.tags,
  author: 'B-Code Team',
  seo: p.seo,
  faq: p.faq,
}));

write(
  '014_seed_blog_posts_batch2.sql',
  `-- Second batch of articles, inserted as drafts (generated by scripts/build-blog-seed.mjs — edit the JS source, not this file).
INSERT INTO blog_posts (slug, title, excerpt, body, cover_url, tags, author, status, seo, faq)
SELECT slug, title, excerpt, body, cover_url, tags, author, 'draft', seo, faq
FROM jsonb_to_recordset($seed$${toJson(batch2)}$seed$::jsonb)
  AS x(slug TEXT, title JSONB, excerpt JSONB, body JSONB, cover_url TEXT, tags JSONB, author TEXT, seo JSONB, faq JSONB)
ON CONFLICT (slug) DO NOTHING;
`,
  batch2.length
);
